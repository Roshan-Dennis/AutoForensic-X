#!/usr/bin/env python3
"""
generate_ticket.py — assembles the NIST-aligned master ticket.md for an
incident from the alert/graph data, the SOAR playbook log, and the four
already-generated Ollama outputs (narrative, Sigma rule, hardening,
executive summary). This is the fifth and final per-incident artifact in
the Ollama/Sigma phase (AutoForensic-X).

Deliberately NOT an LLM call: every fact in this document already came
either straight from Neo4j/the SOAR audit log (ground truth, no
fabrication risk) or from one of the four generator scripts that was
already tested and validated against real incident data. ticket.md is
pure Jinja2 templating over data that's already trustworthy - adding a
fifth Ollama call here would only reintroduce the fabrication risk the
other four scripts spent real debugging effort to rule out, for no
benefit (nothing left to summarize that isn't already summarized).

Usage (from inside soc-dashboard/, same venv as incident_packager.py -
requires jinja2):
    python3 generate_ticket.py <incident_id>

Reads <SAVE_DIR>/<incident_id>/{narrative.md, detection.sigma.yml,
detection.sigma.valid, hardening.md, executive_summary.md} if present
(each is optional - missing ones are noted rather than erroring, so this
can run even if an earlier generator hasn't been run yet for this
incident). Writes <SAVE_DIR>/<incident_id>/ticket.md and prints it.
"""

from __future__ import annotations

import sys

from jinja2 import Template

from incident_packager import SAVE_DIR, build_package

# Hardcoded asset-criticality lookup by hostname, per the roadmap's
# priority-field plan (severity x asset criticality). This is NOT yet
# wired into ingest_wazuh.py/detect_kerberoasting.py as a stored Alert
# property (separate future task) - here it's computed at render time
# from the package's host field, purely for display on the ticket. Never
# invented beyond what this lookup actually states.
ASSET_CRITICALITY = {
    "dc": "critical",
    "target": "standard",
    "kali": "low",
    "soc": "standard",
}

TICKET_TEMPLATE = """\
# Incident Ticket: {{ p.incident_id }}

## 1. Metadata
| Field | Value |
|---|---|
| Incident ID | `{{ p.incident_id }}` |
| Title | {{ p.title }} |
| Detected | {{ p.timestamp }} |
| Host | {{ p.host }} (asset criticality: {{ criticality }}) |
| Severity | {{ p.severity }} |
| MITRE Technique(s) | {{ p.mitre_technique }} |
| MITRE Tactic(s) | {{ p.mitre_tactic }} |
| Detection source | {{ source_plain }} |
| Status | Open — claim/contain/close ticket workflow not yet implemented in the console (see roadmap) |
| Disposition | Pending analyst triage |

## 2. Executive Summary
{{ executive_summary }}

## 3. Triage
- **Corroborating telemetry sources:** {{ p.corroborations }}
- **Entry point:** `{{ p.entry_point }}`
- **Disposition:** Pending analyst triage — the console does not yet have a disposition field (true positive / false positive / benign / duplicate) wired up; this incident is real lab data from a deliberately executed attack technique, not a live triage decision.

## 4. Timeline
| Timestamp | Event |
|---|---|
{% for e in timeline -%}
| {{ e.ts }} | {{ e.event }} |
{% endfor %}

## 5. Technical Analysis
{{ narrative }}

### Root-cause process chain
| Binary | PID | Arguments | Start time |
|---|---|---|---|
{% for proc in p.root_cause_process_chain -%}
| `{{ proc.full_binary or proc.binary }}` | {{ proc.pid }} | {{ (proc.arguments or '—')|truncate(200) }} | {{ proc.start_time or '—' }} |
{% endfor %}

## 6. Indicators of Compromise
- **Entry-point binary:** `{{ p.entry_point }}`
- **Source IP:** {{ p.srcip or 'not recorded (internally correlated detection, no external source IP captured for this event)' }}
- **Host:** {{ p.host }}
{% if p.raw_detail -%}
- **Raw command/detail (verbatim from telemetry):**
  ```
  {{ p.raw_detail }}
  ```
{% endif %}

## 7. Containment, Eradication & Recovery
{% if remediation_lines -%}
{% for line in remediation_lines -%}
- {{ line }}
{% endfor %}
{% else -%}
- No automated remediation action was recorded for this incident.
{% endif %}

### Detection rule (Sigma)
{% if sigma_rule -%}
Validation: **{{ sigma_valid }}**

```yaml
{{ sigma_rule }}
```
{% else -%}
_Not yet generated for this incident — run `generate_sigma.py {{ p.incident_id }}` first._
{% endif %}

## 8. Preventive Recommendations
{{ hardening }}

---
*Generated by AutoForensic-X — ticket.md assembled from Neo4j incident data, the SOAR playbook audit log, and locally-generated AI outputs (narrative, Sigma rule, hardening recommendations, executive summary). No field in this document beyond the AI-authored prose sections (5, 7's prose lead-in if any, and 8) was generated by a language model.*
"""


def _source_plain(package: dict) -> str:
    source = package.get("source")
    if source == "wazuh":
        return "Automatically detected and flagged by Wazuh's native ruleset."
    if source == "graph":
        return (
            "Identified via the custom graph-correlation layer — no native "
            "Wazuh rule fired on this activity."
        )
    return str(source)


def _read_optional(folder, filename: str, missing_note: str) -> str:
    path = folder / filename
    if path.exists():
        return path.read_text().strip()
    return missing_note


def _remediation_lines(package: dict) -> list[str]:
    # Same plain-English translation as generate_executive.py's
    # _remediation_summary(), duplicated rather than imported since this
    # script has no dependency on generate_executive.py and the logic is
    # small - keeps each generator independently runnable.
    events = package.get("remediation_history") or []
    lines = []
    for e in events:
        ts = e.get("ts")
        action = e.get("action")
        status = e.get("status")
        if action == "kill_failed":
            desc = f"the security console attempted to automatically stop the malicious process, which {status}"
        else:
            desc = f"the security console attempted an automated response (action: {action}), which {status}"
        lines.append(f"{ts} — {desc}")
    return lines


def _build_timeline(package: dict) -> list[dict]:
    # Timestamps arrive in mixed types: process-chain start_time and
    # remediation ts are already plain strings, but package["timestamp"]
    # is a raw neo4j.time.DateTime object (build_package() returns live
    # Python objects - only incident_packager callers that round-trip
    # through json.dumps(default=str) ever see it as a string). Sorting a
    # mix of str and DateTime raises TypeError. Normalize every value to
    # str() as it's added rather than trying to sort mixed types, since
    # ISO-8601-with-timezone strings still sort correctly lexicographically.
    events = []
    for proc in package.get("root_cause_process_chain") or []:
        if proc.get("start_time"):
            events.append(
                {
                    "ts": str(proc["start_time"]),
                    "event": f"Process started: `{proc.get('full_binary') or proc.get('binary')}` (pid {proc.get('pid')})",
                }
            )
    if package.get("timestamp"):
        events.append({"ts": str(package["timestamp"]), "event": f"Incident detected: {package.get('title')}"})
    for e in package.get("remediation_history") or []:
        if e.get("ts"):
            events.append(
                {
                    "ts": str(e["ts"]),
                    "event": f"Remediation attempted: {e.get('action')} ({e.get('status')})",
                }
            )
    events.sort(key=lambda e: e["ts"])
    return events


def generate_ticket(incident_id: str) -> str:
    package = build_package(incident_id)
    folder = SAVE_DIR / incident_id.replace("/", "_")

    narrative = _read_optional(
        folder, "narrative.md",
        f"_Not yet generated for this incident — run `generate_narrative.py {incident_id}` first._",
    )
    hardening = _read_optional(
        folder, "hardening.md",
        f"_Not yet generated for this incident — run `generate_hardening.py {incident_id}` first._",
    )
    executive_summary = _read_optional(
        folder, "executive_summary.md",
        f"_Not yet generated for this incident — run `generate_executive.py {incident_id}` first._",
    )
    sigma_rule = None
    sigma_valid = None
    sigma_path = folder / "detection.sigma.yml"
    valid_path = folder / "detection.sigma.valid"
    if sigma_path.exists():
        sigma_rule = sigma_path.read_text().strip()
        if valid_path.exists():
            raw = valid_path.read_text().strip()
            sigma_valid = "PASSED" if raw == "true" else f"FAILED ({raw})"

    host = (package.get("host") or "").lower()
    criticality = ASSET_CRITICALITY.get(host, "unclassified")

    template = Template(TICKET_TEMPLATE, trim_blocks=True, lstrip_blocks=True)
    return template.render(
        p=package,
        criticality=criticality,
        source_plain=_source_plain(package),
        narrative=narrative,
        hardening=hardening,
        executive_summary=executive_summary,
        sigma_rule=sigma_rule,
        sigma_valid=sigma_valid,
        remediation_lines=_remediation_lines(package),
        timeline=_build_timeline(package),
    )


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help"):
        print(__doc__)
        sys.exit(0)

    incident_id = sys.argv[1]
    ticket = generate_ticket(incident_id)
    print(ticket)

    folder = SAVE_DIR / incident_id.replace("/", "_")
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "ticket.md").write_text(ticket)
    print(f"\nSaved to {folder / 'ticket.md'}", file=sys.stderr)


if __name__ == "__main__":
    main()
